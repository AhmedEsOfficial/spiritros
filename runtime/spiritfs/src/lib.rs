//! # `SpiritFS` — Semantic Filesystem
//!
//! `SpiritFS` is a FUSE-based filesystem that augments the traditional POSIX file
//! interface with semantic operations: embedding-based search, automatic tagging,
//! and content-addressable storage.
//!
//! ## Design principles
//!
//! - **POSIX first**: All standard file operations (`open`, `read`, `write`,
//!   `readdir`, etc.) work exactly as expected. `SpiritFS` is a drop-in replacement
//!   for any directory.
//! - **Async semantics**: Embedding generation and semantic indexing happen
//!   asynchronously in background tasks. A `write()` returns immediately; the
//!   embedding is computed later. This preserves invariant #6.
//! - **CAS backend**: File contents are stored in a content-addressable store
//!   (SHA-256 keyed), enabling deduplication and efficient snapshotting.
//!
//! // PHASE1-SHIM: Uses FUSE via the `fuser` crate. Phase 2+ integrates
//! // directly with the `SpiritKernel` VFS layer.

#![warn(clippy::all, clippy::pedantic)]

// ── Modules ──────────────────────────────────────────────────────────────────

/// Core type definitions for the semantic filesystem.
pub mod types {
    use serde::{Deserialize, Serialize};
    use uuid::Uuid;

    /// Unique inode identifier within `SpiritFS`.
    #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
    pub struct InodeId(pub u64);

    /// Content hash used as the CAS key (SHA-256).
    #[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
    pub struct ContentHash(pub [u8; 32]);

    /// Semantic tag automatically assigned by the embedding pipeline.
    #[derive(Debug, Clone, Serialize, Deserialize)]
    pub struct SemanticTag {
        /// Human-readable tag label.
        pub label: String,
        /// Confidence score in [0.0, 1.0].
        pub confidence: f32,
    }

    /// Metadata for a file in `SpiritFS`.
    #[derive(Debug, Clone, Serialize, Deserialize)]
    pub struct FileMeta {
        /// Inode number.
        pub inode: InodeId,
        /// File name.
        pub name: String,
        /// Size in bytes.
        pub size: u64,
        /// Content hash for CAS lookup.
        pub content_hash: Option<ContentHash>,
        /// Embedding vector ID (for semantic search).
        pub embedding_id: Option<Uuid>,
        /// Auto-generated semantic tags.
        pub tags: Vec<SemanticTag>,
    }
}

/// Error types for `SpiritFS` operations.
pub mod error {
    /// Errors that can occur during `SpiritFS` operations.
    #[derive(Debug, thiserror::Error)]
    pub enum SpiritFsError {
        /// FUSE operation failed.
        #[error("FUSE error: {0}")]
        FuseError(String),

        /// Content-addressable storage error.
        #[error("CAS error: {0}")]
        CasError(String),

        /// Inode not found.
        #[error("Inode {0} not found")]
        InodeNotFound(u64),

        /// Semantic index operation failed.
        #[error("Semantic index error: {0}")]
        SemanticIndexError(String),

        /// Embedding generation failed.
        #[error("Embedding generation failed: {0}")]
        EmbeddingError(String),

        /// Configuration error.
        #[error("SpiritFS configuration error: {0}")]
        ConfigError(String),

        /// Underlying I/O error.
        #[error("I/O error: {0}")]
        IoError(#[from] std::io::Error),
    }
}

pub mod fuse_ops {
    //! FUSE filesystem implementation.
    //!
    //! Implements the `fuser::Filesystem` trait for `SpiritFS`.
    //!
    //! This module translates FUSE callbacks into operations on the CAS
    //! backend and semantic index. All POSIX semantics are preserved;
    //! semantic operations run asynchronously via background tasks.
}

pub mod semantic_index {
    //! Semantic index backed by a vector database.
    //!
    //! Manages the embedding index for semantic file search.
    //!
    //! In Phase 1, this integrates with Qdrant (ADR-009) for vector storage
    //! and similarity search. Embeddings are generated by sending file
    //! content to the inference coordinator.
}

pub mod cas {
    //! Content-addressable storage (CAS).
    //!
    //! SHA-256 keyed blob store for file contents.
    //!
    //! Provides deduplication: identical files share the same blob.
    //! Blobs are immutable once written, enabling safe concurrent reads
    //! and efficient snapshot/fork operations.
}

/// Configuration for `SpiritFS`.
pub mod config {
    use serde::{Deserialize, Serialize};

    /// Configuration for the `SpiritFS` filesystem.
    #[derive(Debug, Clone, Serialize, Deserialize)]
    pub struct SpiritFsConfig {
        /// Mount point path.
        pub mount_point: String,
        /// CAS storage directory.
        pub cas_dir: String,
        /// Qdrant endpoint for semantic index.
        pub qdrant_url: String,
        /// Model to use for embedding generation.
        pub embedding_model: String,
        /// Maximum file size eligible for automatic embedding (bytes).
        pub max_embedding_file_size: u64,
    }

    impl Default for SpiritFsConfig {
        fn default() -> Self {
            Self {
                mount_point: "/mnt/spiritfs".to_string(),
                cas_dir: "/var/lib/spiritfs/cas".to_string(),
                qdrant_url: "http://127.0.0.1:6334".to_string(),
                embedding_model: "nomic-embed-text".to_string(),
                max_embedding_file_size: 10 * 1024 * 1024, // 10 MiB
            }
        }
    }
}

