// ── Tests ────────────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_spiritfs_config_default_has_sane_mount_point() {
        let cfg = SpiritFsConfig::default();
        assert!(!cfg.mount_point.is_empty());
        assert!(cfg.mount_point.starts_with('/'));
    }

    #[test]
    fn test_inode_id_equality() {
        let a = InodeId(42);
        let b = InodeId(42);
        let c = InodeId(99);
        assert_eq!(a, b);
        assert_ne!(a, c);
    }

    #[test]
    fn test_content_hash_equality() {
        let hash_a = ContentHash([0xAB; 32]);
        let hash_b = ContentHash([0xAB; 32]);
        let hash_c = ContentHash([0xCD; 32]);
        assert_eq!(hash_a, hash_b);
        assert_ne!(hash_a, hash_c);
    }

    #[test]
    fn test_semantic_tag_serialization_roundtrip() {
        let tag = SemanticTag {
            label: "rust-code".to_string(),
            confidence: 0.95,
        };
        let json = serde_json::to_string(&tag).expect("serialize");
        let back: SemanticTag = serde_json::from_str(&json).expect("deserialize");
        assert_eq!(tag.label, back.label);
        assert!((tag.confidence - back.confidence).abs() < f32::EPSILON);
    }

    #[test]
    fn test_spiritfs_error_display() {
        let err = SpiritFsError::InodeNotFound(42);
        assert!(err.to_string().contains("42"));
    }
}
